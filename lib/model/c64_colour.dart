/// Selects one of the sixteen VIC-II colours without `model/` importing
/// Flutter. `ui/theme.dart` is the only place that maps a value here to an
/// actual `Color` (and to a contrasting ink colour for tile text).
enum C64Colour {
  black,
  white,
  red,
  cyan,
  purple,
  green,
  blue,
  yellow,
  orange,
  brown,
  lightRed,
  darkGrey,
  grey,
  lightGreen,
  lightBlue,
  lightGrey,
}
